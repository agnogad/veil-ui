import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

export interface FrameworkSourceFile {
  name: string;
  content: string;
}

export interface ComponentFrameworkSources {
  vue?: FrameworkSourceFile[];
  html?: FrameworkSourceFile[];
}

type FrameworkSourceMap = Record<string, ComponentFrameworkSources>;

let cache: FrameworkSourceMap | null = null;

function load(): FrameworkSourceMap {
  if (cache) return cache;

  const candidates = [
    path.join(process.cwd(), "lib/generated/framework-source.json"),
    path.join(process.cwd(), "apps/docs/lib/generated/framework-source.json"),
  ];
  const file = candidates.find((candidate) => existsSync(candidate));

  if (!file) return (cache = {});

  try {
    cache = JSON.parse(readFileSync(file, "utf8")) as FrameworkSourceMap;
  } catch {
    cache = {};
  }
  return cache;
}

/** Generated by `pnpm registry:build`; absent until the first build. */
export function getComponentFrameworkSources(
  name: string,
): ComponentFrameworkSources | null {
  const sources = load()[name];
  if (!sources) return null;
  if (!sources.vue && !sources.html) return null;
  return sources;
}
